import {isAbsolute, relative} from 'node:path';
import type {MessageItem, PlanStep, TurnView} from '../shared/types.js';
import {applyPlan, isNextStepTool, isPlanTool, nextStep} from './claude-progress.js';

/** A message as returned by the Agent SDK's getSessionMessages. */
export type ClaudeMessage = {type: string; uuid: string; message?: unknown; parent_tool_use_id?: string | null};
type Block = {type?: string; text?: string; thinking?: string; id?: string; name?: string; input?: Record<string, unknown>;
  tool_use_id?: string; content?: unknown; is_error?: boolean; source?: {type?: string; media_type?: string; data?: string}};

const MAX_TOOL_TEXT = 4000;
const MAX_INLINE_IMAGE = 2 * 1024 * 1024;
const fileTools = new Set(['Edit', 'Write', 'MultiEdit', 'NotebookEdit']);
const searchTools = new Set(['Grep', 'Glob', 'LS']);
const PLAN_MARKS: Record<PlanStep['status'], string> = {completed: '[x]', in_progress: '[~]', pending: '[ ]'};

function clip(text: string, max = MAX_TOOL_TEXT) {return text.length > max ? text.slice(0, max) + '\n…' : text;}
const str = (value: unknown) => typeof value === 'string' ? value : '';

function blocks(message: unknown): Block[] {
  const content = (message as {content?: unknown} | undefined)?.content;
  if (typeof content === 'string') return [{type: 'text', text: content}];
  return Array.isArray(content) ? content.filter(block => block && typeof block === 'object') : [];
}

function resultText(content: unknown): string {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  return content.map(part => part?.type === 'text' ? str(part.text) : part?.type === 'image' ? '[图片]' : '').filter(Boolean).join('\n');
}

/** Maps a Claude Code tool call to the activity kinds the Codex conversation view already renders. */
export function toolActivity(block: Block): Pick<MessageItem, 'type' | 'text' | 'files'> {
  const name = str(block.name) || '工具', input = block.input || {};
  const path = str(input.file_path) || str(input.notebook_path) || str(input.path);
  if (name === 'Bash' || name === 'PowerShell') return {type: 'commandExecution', text: `$ ${str(input.command)}`};
  if (fileTools.has(name)) return {type: 'fileChange', text: path, files: path ? [path] : undefined};
  if (name === 'Read') return {type: 'fileRead', text: path, files: path ? [path] : undefined};
  if (searchTools.has(name)) return {type: 'codeSearch', text: [str(input.pattern), str(input.path)].filter(Boolean).join('  ')};
  if (name === 'WebSearch' || name === 'WebFetch') return {type: 'webSearch', text: str(input.query) || str(input.url)};
  if (name === 'TodoWrite' && Array.isArray(input.todos)) {
    const marks: Record<string, string> = {completed: '[x]', in_progress: '[~]'};
    return {type: 'plan', text: input.todos.map((todo: any) => `${marks[todo?.status] || '[ ]'} ${str(todo?.content)}`).join('\n')};
  }
  if (name === 'Task' || name === 'Agent') return {type: 'subagent', text: str(input.description) || str(input.prompt).slice(0, 200)};
  return {type: 'toolCall', text: `${name} ${clip(JSON.stringify(input), 300)}`};
}

function imageUrl(block: Block) {
  const source = block.source;
  if (source?.type !== 'base64' || typeof source.data !== 'string' || !/^image\/(png|jpeg|gif|webp)$/.test(str(source.media_type))) return '';
  return source.data.length * 0.75 <= MAX_INLINE_IMAGE ? `data:${source.media_type};base64,${source.data}` : '';
}

/** Claude Code wraps slash commands and their output in tags; show them as the user typed them. */
function commandText(text: string): {text: string; kind: 'user' | 'status' | 'skip'} {
  if (/^Caveat: The messages below were generated by the user while running local commands/.test(text)) return {text: '', kind: 'skip'};
  // The desktop app puts context (a scratch-workspace note, the Artifact being viewed) ahead of what the user typed.
  const typed = text.replace(/^\s*(?:<(system-reminder|artifact-view-context)\b[^>]*>[\s\S]*?<\/\1>\s*)+/, '');
  if (typed !== text) return typed.trim() ? commandText(typed) : {text: '', kind: 'skip'};
  if (/^\s*<create-pr-command>/.test(text)) return {text: '创建 PR', kind: 'user'};
  // Claude Code reports a finished background command or agent to the model as a user-role message; the user never typed it.
  if (/^\s*<task-notification>/.test(text)) {
    const summary = /<summary>([\s\S]*?)<\/summary>/.exec(text)?.[1]?.trim();
    return {text: clip(summary || '后台任务已结束', 600), kind: 'status'};
  }
  // After compacting, Claude Code hands the model a summary of the earlier conversation as a user message (sometimes behind
  // a short notice); the compact boundary just before it already shows as "整理上下文".
  if (/^[\s\S]{0,600}?This session is being continued from a previous conversation that ran out of context\./.test(text)) return {text: '', kind: 'skip'};
  // A subagent's hand-back or another session's message, and the desktop app's CI monitor events, are not the user's either.
  if (/^\s*(?:Another Claude session sent a message:|<agent-message[\s>])/.test(text)) {
    return {text: /\[Subagent hand-back\]/.test(text) ? '子 Agent 已交回结果' : '收到另一个 Claude 会话的消息', kind: 'status'};
  }
  if (/^\s*<ci-monitor-event>/.test(text)) return {text: 'CI 监控通知', kind: 'status'};
  const name = /<command-name>([\s\S]*?)<\/command-name>/.exec(text)?.[1];
  if (name) {
    const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1]?.trim();
    return {text: [name.trim(), args].filter(Boolean).join(' '), kind: 'user'};
  }
  const output = /<local-command-(?:stdout|stderr)>([\s\S]*?)<\/local-command-(?:stdout|stderr)>/.exec(text)?.[1];
  if (output !== undefined) return output.trim() ? {text: clip(output.trim(), 600), kind: 'status'} : {text: '', kind: 'skip'};
  return {text, kind: 'user'};
}

const interrupted = /^\[Request interrupted by user[^\]]*\]$/;
const ARTIFACT_URL = /https:\/\/claude\.ai\/artifact\/[A-Za-z0-9_-]{8,64}/g;
const artifactUrl = (value: string) => /^https:\/\/claude\.ai\/artifact\/[A-Za-z0-9_-]{8,64}$/.test(value) ? value : '';
/** Artifact publishes and opens, and writes to an Artifact's data, change what its page shows; reads and listings do not. */
function changesArtifact(block: Block) {
  const input = block.input || {}, action = str(input.action);
  if (block.name === 'Artifact') return !action || action === 'publish' || action === 'open';
  if (block.name === 'ArtifactData') return Boolean(artifactUrl(str(input.url))) && !['get', 'list', 'query'].includes(action);
  return false;
}
/** Calls that put the page in front of the user in Claude's own app: a publish of the page (not an asset upload) and an explicit open. */
function showsArtifact(block: Block) {
  const input = block.input || {}, action = str(input.action);
  return block.name === 'Artifact' && (action === 'open' || (!action || action === 'publish') && input.asset !== true);
}

/**
 * Groups a Claude Code transcript into Codex-style turns: a turn starts with each prompt the user typed;
 * tool results returned to the model stay inside the tool call they answer.
 */
/**
 * File edits as unified diffs, by tool call. The SDK's messages leave out what each edit changed;
 * the raw transcript keeps it (`toolUseResult.structuredPatch`, or the content of a created file).
 */
export function claudePatches(transcript: string, cwd = ''): Map<string, string> {
  const patches = new Map<string, string>();
  for (const line of transcript.split('\n')) {
    if (!line.includes('"toolUseResult"') || !line.includes('"filePath"')) continue;
    let entry: any;
    try {entry = JSON.parse(line);} catch {continue;}
    const result = entry?.toolUseResult, content = entry?.message?.content;
    if (!result || typeof result.filePath !== 'string' || !Array.isArray(content)) continue;
    const id = content.find((block: Block) => block?.type === 'tool_result' && block.tool_use_id)?.tool_use_id;
    if (!id) continue;
    const near = cwd && isAbsolute(result.filePath) ? relative(cwd, result.filePath) : '';
    const path = (near && !near.startsWith('..') && !isAbsolute(near) ? near : result.filePath).split('\\').join('/').replace(/^\/+/, '');
    const header = `diff --git a/${path} b/${path}\n`;
    let text = '';
    if (result.type === 'create' && typeof result.content === 'string') {
      const lines = result.content.replace(/\r?\n$/, '').split(/\r?\n/);
      text = `${header}new file mode 100644\n--- /dev/null\n+++ b/${path}\n@@ -0,0 +1,${lines.length} @@\n${lines.map((value: string) => '+' + value).join('\n')}\n`;
    } else if (Array.isArray(result.structuredPatch) && result.structuredPatch.length) {
      const hunks = result.structuredPatch.filter((hunk: any) => Array.isArray(hunk?.lines)).map((hunk: any) =>
        `@@ -${hunk.oldStart},${hunk.oldLines} +${hunk.newStart},${hunk.newLines} @@\n${hunk.lines.join('\n')}\n`);
      if (hunks.length) text = `${header}--- a/${path}\n+++ b/${path}\n${hunks.join('')}`;
    }
    if (text && text.length <= 200_000) patches.set(String(id), text);
  }
  return patches;
}
const MAX_TURN_DIFF = 600_000;

/**
 * Artifact names, by page URL, from every Artifact call in the raw transcript. The SDK's messages follow only the
 * current branch, so the call that created a page and named it (`title`) can be missing from them.
 */
export function claudeArtifactTitles(transcript: string): Map<string, string> {
  const calls = new Map<string, Record<string, unknown>>(), titles = new Map<string, string>();
  for (const line of transcript.split('\n')) {
    if (!line.includes('claude.ai/artifact/')) continue;
    let entry: any;
    try {entry = JSON.parse(line);} catch {continue;}
    for (const block of blocks(entry?.message)) {
      if (block.type === 'tool_use' && block.name === 'Artifact' && block.id && str(block.input?.title).trim()) calls.set(block.id, block.input!);
      if (block.type !== 'tool_result' || !block.tool_use_id || block.is_error) continue;
      const input = calls.get(block.tool_use_id);
      if (!input) continue;
      const typeUrl = str(input.type_url);
      const url = artifactUrl(str(input.url)) || [...resultText(block.content).matchAll(ARTIFACT_URL)].map(match => match[0]).find(found => found !== typeUrl);
      if (url) titles.set(url, str(input.title).trim().slice(0, 200));
    }
  }
  return titles;
}

/** What a session last ran with, as Claude Code (the CLI or the desktop app) records it in the transcript; '' where it says nothing. */
export type ClaudeRecordedSettings = {model: string; effort: string; permissionMode: string};

/** Where each setting is recorded. A setting the session view shows belongs here, so a session run elsewhere shows it too. */
const RECORDED: {[K in keyof ClaudeRecordedSettings]: (entry: any) => string} = {
  // The model of the latest reply; "<synthetic>" marks a message Claude Code wrote itself (an interruption, an API error).
  model: entry => entry.type === 'assistant' && entry.message?.model !== '<synthetic>' ? str(entry.message?.model) : '',
  effort: entry => entry.type === 'assistant' ? str(entry.effort) || str(entry.perTurnEffort) : '',
  // Written on each prompt the user sends.
  permissionMode: entry => entry.type === 'user' ? str(entry.permissionMode) : '',
};
const RECORDED_KEYS = Object.keys(RECORDED) as (keyof ClaudeRecordedSettings)[];

/** Each setting's latest value, read from the end of the transcript; a subagent's entries do not count. */
export function claudeRecordedSettings(transcript: string): ClaudeRecordedSettings {
  const found: ClaudeRecordedSettings = {model: '', effort: '', permissionMode: ''};
  const lines = transcript.split('\n');
  for (let index = lines.length - 1; index >= 0 && RECORDED_KEYS.some(key => !found[key]); index--) {
    const line = lines[index];
    if (!/"(?:model|effort|perTurnEffort|permissionMode)":"/.test(line)) continue;
    let entry: any;
    try {entry = JSON.parse(line);} catch {continue;}
    if (!entry || typeof entry !== 'object' || entry.isSidechain) continue;
    for (const key of RECORDED_KEYS) if (!found[key]) found[key] = RECORDED[key](entry);
  }
  return found;
}

/**
 * The folder a session works in, as Claude Code records it: where it was last moved to, else the first entry that names one.
 * The Agent SDK reads it from the transcript's first 64 KiB only, which a first prompt carrying an image can fill on its own.
 */
export function claudeTranscriptCwd(transcript: string): string | undefined {
  let first: string | undefined, moved: string | undefined;
  for (const line of transcript.split('\n')) {
    if (!line.includes('"relocatedCwd"') && (first !== undefined || !line.includes('"cwd"'))) continue;
    let entry: any;
    try {entry = JSON.parse(line);} catch {continue;}
    if (!entry || typeof entry !== 'object') continue;
    if (entry.type === 'relocated' && typeof entry.relocatedCwd === 'string' && entry.relocatedCwd) moved = entry.relocatedCwd;
    if (first === undefined && typeof entry.cwd === 'string' && entry.cwd) first = entry.cwd;
  }
  return moved || first;
}

/**
 * What the session said before it was compacted. The Agent SDK returns only the branch since the latest compact boundary;
 * each boundary names the entry the conversation went on from (`logicalParentUuid`), so the earlier branch is walked back
 * from there, across older boundaries too. Entries the SDK already returned (those a compaction kept) are left out.
 */
export function claudeEarlierMessages(transcript: string, messages: ClaudeMessage[]): ClaudeMessage[] {
  const first = messages[0];
  if (first?.type !== 'system' || !transcript.includes('"logicalParentUuid"')) return [];
  const entries = new Map<string, any>();
  for (const line of transcript.split('\n')) {
    if (!line.includes('"uuid"')) continue;
    let entry: any;
    try {entry = JSON.parse(line);} catch {continue;}
    if (entry && typeof entry.uuid === 'string') entries.set(entry.uuid, entry);
  }
  const known = new Set(messages.map(entry => entry.uuid)), seen = new Set<string>(), earlier: ClaudeMessage[] = [];
  let uuid: unknown = entries.get(first.uuid)?.logicalParentUuid;
  while (typeof uuid === 'string' && !seen.has(uuid)) {
    seen.add(uuid);
    const entry = entries.get(uuid);
    if (!entry) break;
    const boundary = entry.type === 'system' && entry.subtype === 'compact_boundary';
    if (!entry.isSidechain && !known.has(uuid) && (entry.type === 'user' || entry.type === 'assistant' || boundary))
      earlier.push({type: entry.type, uuid, message: entry.message, parent_tool_use_id: null});
    uuid = entry.parentUuid ?? (boundary ? entry.logicalParentUuid : undefined);
  }
  return earlier.reverse();
}

/** `titles`: names known from elsewhere (the raw transcript, a saved snapshot), used where the messages give none. */
export function claudeTurns(messages: ClaudeMessage[], running = false, patches?: Map<string, string>, titles?: Map<string, string>,
  /** When the transcript entry with this uuid was written (ISO), or ''. */
  timeOf?: (uuid: string) => string): TurnView[] {
  const turns: TurnView[] = [];
  const tools = new Map<string, MessageItem>();
  // Calls still waiting for their result, in call order: the latest is what a running turn is doing.
  const open = new Map<string, {item: MessageItem; turn: TurnView; entry: string; text: string}>();
  // A plan carries across turns: the desktop app's update_plan can change the last one by step number.
  let plan: PlanStep[] | undefined;
  // claude.ai Artifacts a turn created or changed, shown under the turn like Codex's file-change card.
  const pageCalls = new Map<string, {turn: TurnView; input: Record<string, unknown>; id: string; shown: boolean}>();
  const pageTitles = new Map<string, string>(titles);
  const toolTurns = new Map<string, TurnView>();
  let turn: TurnView | undefined;
  const current = (id: string) => {
    if (!turn) {turn = {id, status: 'completed', items: [], canFork: false};turns.push(turn);}
    return turn;
  };
  for (const entry of messages) {
    if (entry.parent_tool_use_id) continue; // Subagent internals are summarised by their Task call.
    take(entry);
    // An entry belongs to the turn open after it; a fork copies the transcript up to the turn's last entry.
    if (turn) turn.anchor = entry.uuid;
  }
  for (const item of turns) item.canFork = Boolean(item.anchor) && item.status !== 'inProgress';
  const last = turns.at(-1);
  if (last && running && last.status === 'completed') {last.status = 'inProgress';last.canFork = false;}
  if (last?.status === 'inProgress') {
    const call = [...open.values()].findLast(value => value.turn === last), at = timeOf?.(call?.entry || last.anchor || '');
    last.step = {text: call?.text || '', ...(call ? {type: call.item.type, item: call.item.id} : {}), ...(at ? {startedAt: at} : {})};
  }
  // A page named after it first appeared takes that name everywhere.
  for (const item of turns) for (const page of item.pages || []) page.title = pageTitles.get(page.url) || page.title;
  // Pages published in earlier turns are repeated on the newest one, latest first, so the session's pages stay in reach.
  if (last) {
    const shown = new Set((last.pages || []).map(page => page.url)), earlier: {url: string; title: string; earlier: true}[] = [];
    for (const item of turns.slice(0, -1).reverse()) for (const page of item.pages || []) {
      if (shown.has(page.url)) continue;
      shown.add(page.url);
      earlier.push({url: page.url, title: page.title, earlier: true});
    }
    if (earlier.length) last.pages = [...(last.pages || []), ...earlier];
  }
  return turns;

  function addPage(turn: TurnView, input: Record<string, unknown>, result: string, id: string, shown: boolean) {
    const typeUrl = str(input.type_url);
    const url = artifactUrl(str(input.url)) || [...result.matchAll(ARTIFACT_URL)].map(match => match[0]).find(found => found !== typeUrl);
    if (!url) return;
    if (str(input.title)) pageTitles.set(url, str(input.title).slice(0, 200));
    const pages = turn.pages ??= [];
    const page = pages.find(item => item.url === url);
    if (!page) pages.push({url, title: pageTitles.get(url) || '', changed: id, ...(shown ? {shown: id} : {})});
    else {
      if (pageTitles.has(url)) page.title = pageTitles.get(url)!;
      page.changed = id;
      if (shown) page.shown = id;
    }
  }

  function take(entry: ClaudeMessage) {
    const list = blocks(entry.message);
    if (entry.type === 'system') {
      current(entry.uuid).items.push({id: entry.uuid, type: 'contextCompaction', role: 'activity', text: '整理上下文'});
      return;
    }
    if (entry.type === 'user') {
      const texts: string[] = [], images: string[] = [];
      let stopped = false, status = '';
      for (const block of list) {
        if (block.type === 'tool_result' && block.tool_use_id) {
          const tool = tools.get(block.tool_use_id);
          const output = clip(resultText(block.content).trim());
          if (tool && output) tool.text = tool.text ? `${tool.text}\n${output}` : output;
          if (tool && block.is_error) tool.text = `${tool.text}\n（失败）`;
          open.delete(block.tool_use_id);
          const patch = patches?.get(block.tool_use_id), owner = toolTurns.get(block.tool_use_id);
          if (patch && owner && !block.is_error && (owner.diff?.length || 0) + patch.length <= MAX_TURN_DIFF) owner.diff = (owner.diff || '') + patch;
          const call = pageCalls.get(block.tool_use_id);
          if (call && !block.is_error) addPage(call.turn, call.input, resultText(block.content), call.id, call.shown);
        } else if (block.type === 'text' && block.text?.trim()) {
          if (interrupted.test(block.text.trim())) {stopped = true;continue;}
          const command = commandText(block.text);
          if (command.kind === 'user') texts.push(command.text);
          else if (command.kind === 'status') status = command.text;
        } else if (block.type === 'image') {
          const url = imageUrl(block);
          if (url) images.push(url);
          else texts.push('[图片]');
        }
      }
      if (stopped && turn) turn.status = 'interrupted';
      if (texts.length || images.length) {
        turn = undefined;
        current(entry.uuid).items.push({id: entry.uuid, type: 'userMessage', role: 'user', text: texts.join('\n\n'), ...(images.length ? {images} : {})});
      }
      if (status) current(entry.uuid).items.push({id: entry.uuid + ':out', type: 'status', role: 'status', text: status});
      return;
    }
    if (entry.type !== 'assistant') return;
    const target = current(entry.uuid);
    list.forEach((block, index) => {
      const id = `${entry.uuid}:${index}`;
      if (block.type === 'text' && block.text?.trim()) {
        const last = target.items.at(-1);
        // The CLI writes one line per content block; adjacent text blocks belong to one reply.
        if (last?.role === 'assistant') last.text += '\n\n' + block.text;
        else target.items.push({id, type: 'agentMessage', role: 'assistant', text: block.text});
      } else if (block.type === 'thinking' && block.thinking?.trim()) {
        target.items.push({id, type: 'reasoning', role: 'activity', text: block.thinking});
      } else if (block.type === 'tool_use') {
        const item: MessageItem = {id, role: 'activity', ...toolActivity(block)};
        if (!item.files) delete item.files;
        target.items.push(item);
        if (isPlanTool(block.name)) {
          const next = applyPlan(plan, block.name, block.input);
          if (next) {
            plan = target.plan = next;
            item.type = 'plan';
            item.text = next.map(step => `${PLAN_MARKS[step.status]} ${step.text}`).join('\n');
          }
        }
        if (isNextStepTool(block.name)) {
          const card = nextStep(block.input);
          if (card) {
            target.nextStep = card;
            item.type = 'nextStep';
            item.text = [card.recap, card.ask, card.actions.map(action => `[${action.label}]`).join(' ')].filter(Boolean).join('\n\n');
          }
        }
        if (block.id) {
          tools.set(block.id, item);toolTurns.set(block.id, target);
          open.set(block.id, {item, turn: target, entry: entry.uuid, text: (str(block.input?.description) || '').trim().slice(0, 200)});
        }
        if (block.id && changesArtifact(block)) pageCalls.set(block.id, {turn: target, input: block.input || {}, id: block.id, shown: showsArtifact(block)});
      }
    });
  }
}
